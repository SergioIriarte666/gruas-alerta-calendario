CREATE OR REPLACE FUNCTION public.check_inventory_alerts()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  item_record RECORD;
  alert_record RECORD;
BEGIN
  -- Get item details
  SELECT * INTO item_record FROM public.inventory_items WHERE id = NEW.item_id;
  
  -- Check low stock alerts
  IF NEW.current_quantity <= item_record.minimum_stock THEN
    INSERT INTO public.notification_logs (user_id, type, title, body, data)
    SELECT 
      p.id,
      'inventory_alert',
      'Stock Bajo: ' || item_record.name,
      'El producto ' || item_record.name || ' tiene stock bajo (' || NEW.current_quantity || ' unidades)',
      jsonb_build_object('item_id', NEW.item_id, 'location_id', NEW.location_id, 'quantity', NEW.current_quantity)
    FROM public.profiles p 
    WHERE p.role IN ('admin', 'operator');
  END IF;
  
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_crane_expiry_on_document_upload()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  -- Update the corresponding expiry date in cranes table
  IF NEW.document_type = 'technical_review' AND NEW.expiry_date IS NOT NULL THEN
    UPDATE public.cranes 
    SET technical_review_expiry = NEW.expiry_date, updated_at = now()
    WHERE id = NEW.crane_id;
  ELSIF NEW.document_type = 'insurance' AND NEW.expiry_date IS NOT NULL THEN
    UPDATE public.cranes 
    SET insurance_expiry = NEW.expiry_date, updated_at = now()
    WHERE id = NEW.crane_id;
  ELSIF NEW.document_type = 'circulation_permit' AND NEW.expiry_date IS NOT NULL THEN
    UPDATE public.cranes 
    SET circulation_permit_expiry = NEW.expiry_date, updated_at = now()
    WHERE id = NEW.crane_id;
  END IF;
  
  RETURN NEW;
END;
$$;

-- 2. DESHABILITAR COMPLETAMENTE EL ACCESO ANÓNIMO
-- Esto elimina cualquier residuo de acceso anónimo

-- Deshabilitar registro anónimo en auth
UPDATE auth.config SET anonymous_signups_enabled = false WHERE 1=1;

-- Eliminar cualquier política que pueda haber quedado con acceso anónimo
DO $$
DECLARE
    pol_record RECORD;
BEGIN
    -- Buscar y eliminar cualquier política que permita acceso anónimo
    FOR pol_record IN 
        SELECT schemaname, tablename, policyname 
        FROM pg_policies 
        WHERE schemaname IN ('public', 'storage')
        AND (
          'anon' = ANY(roles) OR 
          roles IS NULL OR 
          array_length(roles, 1) IS NULL
        )
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON %s.%I', 
                      pol_record.policyname, 
                      pol_record.schemaname, 
                      pol_record.tablename);
        RAISE NOTICE 'Eliminada política con acceso anónimo: %.%', pol_record.tablename, pol_record.policyname;
    END LOOP;
END $$;

-- 3. RECREAR POLÍTICAS DE STORAGE SIN ACCESO ANÓNIMO
-- Las políticas de storage deben ser específicamente para authenticated

-- Eliminar políticas de storage existentes
DROP POLICY IF EXISTS "authenticated_users_storage_select" ON storage.objects;
