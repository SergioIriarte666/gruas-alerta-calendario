import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
CREATE SCHEMA cron;
CREATE TABLE cron.job(jobid bigint, jobname text, command text);
INSERT INTO cron.job VALUES(5,'scheduled-backup-email-hourly','SELECT net.http_post(body := ''{}'');');
CREATE FUNCTION cron.alter_job(jobid bigint, command text) RETURNS void LANGUAGE sql AS $$ UPDATE cron.job SET command=alter_job.command WHERE jobid=alter_job.jobid $$;
CREATE TABLE a_empty(id int primary key);
CREATE TABLE b_large(id int primary key, payload text, location double precision);
INSERT INTO b_large SELECT i, repeat('á 漢 '' salto' || chr(10),100), -70.12345678901234 FROM generate_series(1,21) i;
CREATE TABLE c_last(id int primary key); INSERT INTO c_last VALUES(1);`);
await db.exec(readFileSync('supabase/migrations/20261011190000_backup_bounded_chunks.sql','utf8'));
assert.ok((await db.query('SELECT command FROM cron.job')).rows[0].command.includes('timeout_milliseconds := 120000'));
let table=null, offset=0, sql='', blocks=0;
const counts={};
do {
 const {rows:[chunk]}=await db.query('SELECT * FROM backup_dump_chunk_v2($1,$2,$3,$4)',[table,3000,5,offset]);
 assert.ok(Buffer.byteLength(chunk.body)<8000,'respuesta acotada incluso para una tabla grande');
 sql+=chunk.body;
 for(const [t,n] of Object.entries(chunk.rows_by_table)) counts[t]=(counts[t]??0)+Number(n);
 table=chunk.next_table; offset=Number(chunk.next_offset);
 assert.ok(++blocks<100,'cursor termina');
} while(table);
assert.deepEqual(counts,{a_empty:0,b_large:21,c_last:1});
assert.equal((sql.match(/-- ===== b_large =====/g)??[]).length,1);
assert.ok(sql.includes('-- 21 filas\n'));
await db.exec('TRUNCATE b_large,c_last;');
await db.exec(sql);
assert.equal((await db.query('SELECT count(*)::int AS n FROM b_large')).rows[0].n,21);
assert.equal((await db.query('SELECT location FROM b_large LIMIT 1')).rows[0].location,-70.12345678901234);
await assert.rejects(db.query("SELECT * FROM backup_dump_chunk_v2('inexistente',3000,5,0)"));
console.log(`SQL paginado y restauración verificados (${blocks} bloques).`);
await db.close();
