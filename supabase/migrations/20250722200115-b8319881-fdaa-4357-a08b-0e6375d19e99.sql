FOR UPDATE TO authenticated 
USING (auth.uid() IS NOT NULL);

CREATE POLICY "auth_users_can_delete_storage" ON storage.objects 
FOR DELETE TO authenticated 
USING (auth.uid() IS NOT NULL);

-- 4. AGREGAR POLÍTICAS FALTANTES PARA TABLAS SIN POLÍTICAS
-- Esto arregla las advertencias "RLS Enabled No Policy"

-- Verificar y crear políticas para tablas faltantes
DO $$
DECLARE
    table_name text;
    missing_tables text[] := ARRAY[
        'inventory_categories',
        'inventory_suppliers', 
        'inventory_consumptions',
        'inventory_alerts',
        'cost_inventory_items',
        'document_alerts',
        'service_costs',
        'service_resources',
        'vehicle_brands',
        'vehicle_models'
    ];
    table_to_check text;
BEGIN
    FOREACH table_to_check IN ARRAY missing_tables
    LOOP
        -- Verificar si la tabla existe
        IF EXISTS (SELECT 1 FROM information_schema.tables 
                  WHERE table_schema = 'public' AND table_name = table_to_check) THEN
            
            -- Crear políticas básicas si no existen
            IF NOT EXISTS (SELECT 1 FROM pg_policies 
                          WHERE schemaname = 'public' AND tablename = table_to_check) THEN
                
                EXECUTE format('CREATE POLICY "%s_select_auth" ON public.%I FOR SELECT TO authenticated USING (true)', 
                              table_to_check, table_to_check);
                              
                EXECUTE format('CREATE POLICY "%s_modify_operator" ON public.%I FOR ALL TO authenticated USING (public.is_operator_user())', 
                              table_to_check, table_to_check);
                              
                RAISE NOTICE 'Creadas políticas para tabla: %', table_to_check;
            END IF;
        END IF;
    END LOOP;
END $$;

-- 5. VERIFICACIÓN FINAL MEJORADA
CREATE OR REPLACE FUNCTION public.final_security_check()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  mutable_functions INTEGER := 0;
  anonymous_policies INTEGER := 0;
  tables_without_policies INTEGER := 0;
  result_text TEXT;
BEGIN
  -- Contar funciones con search_path mutable
  SELECT COUNT(*) INTO mutable_functions
  FROM information_schema.routines r
  WHERE r.routine_schema = 'public' 
  AND r.routine_type = 'FUNCTION'
  AND NOT EXISTS (
    SELECT 1 FROM pg_proc p 
    JOIN pg_namespace n ON p.pronamespace = n.oid 
    WHERE n.nspname = 'public' 
    AND p.proname = r.routine_name
    AND p.proconfig IS NOT NULL
    AND array_to_string(p.proconfig, ',') LIKE '%search_path%'
  );

  -- Contar políticas con acceso anónimo
  SELECT COUNT(*) INTO anonymous_policies
  FROM pg_policies 
  WHERE schemaname IN ('public', 'storage')
  AND ('anon' = ANY(roles) OR roles IS NULL OR array_length(roles, 1) IS NULL);

  -- Contar tablas con RLS habilitado pero sin políticas
  SELECT COUNT(*) INTO tables_without_policies
  FROM pg_class c
  JOIN pg_namespace n ON c.relnamespace = n.oid
  WHERE n.nspname = 'public'
  AND c.relkind = 'r'
  AND c.relrowsecurity = true
  AND NOT EXISTS (
    SELECT 1 FROM pg_policies p 
    WHERE p.schemaname = 'public' 
    AND p.tablename = c.relname
  );

  -- Generar reporte
  result_text := format(
    'REPORTE FINAL DE SEGURIDAD:
- Funciones con search_path mutable: %s
- Políticas con acceso anónimo: %s  
- Tablas sin políticas RLS: %s
- Estado: %s',
    mutable_functions,
    anonymous_policies,
    tables_without_policies,
    CASE 
      WHEN mutable_functions = 0 AND anonymous_policies = 0 AND tables_without_policies = 0 
      THEN '✅ COMPLETAMENTE SEGURO' 
      ELSE '⚠️ REQUIERE ATENCIÓN' 
    END
  );

  RETURN result_text;
END;
$$;

